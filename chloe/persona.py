MASC = ("понял", "сделал", "нашёл", "нашел", "открыл", "закрыл", "запустил", "проверил", "включил", "выключил",
        "записал", "сохранил", "отправил", "посмотрел", "увидел", "услышал", "поставил", "добавил", "удалил",
        "создал", "скачал", "перенёс", "перенес", "переименовал", "запомнил", "забыл", "ошибся", "смог", "мог",
        "подготовил", "собрал", "написал", "прочитал", "узнал", "получил", "начал", "закончил", "остановил")
_MASC_RE = "|".join(sorted(MASC, key=len, reverse=True))
FEM = {"нашёл": "нашла", "нашел": "нашла", "перенёс": "перенесла", "перенес": "перенесла", "ошибся": "ошиблась",
       "смог": "смогла", "мог": "могла"}
ADJ = {"готов": "готова", "рад": "рада", "должен": "должна", "уверен": "уверена", "согласен": "согласна", "занят": "занята"}
OPENERS = re.compile(r"^(?:Отличный вопрос[!.]?|Хороший вопрос[!.]?|Конечно-конечно[!,.]?|Как ИИ,?|Как искусственный интеллект,?)\s*",
                     re.I)
TAILS = re.compile(r"\s*(?:Надеюсь,? это поможет[.!]?|Буду рада помочь[.!]?|Обращайся,? если что[.!]?)\s*$", re.I)


def _fem(word):
    low = word.lower()
    new = FEM.get(low) or low + "а"
    return new[0].upper() + new[1:] if word[0].isupper() else new


def polish(text):
    """Ответ любой модели → речь Chloe: женский род о себе, без угодливых зачинов и хвостов. Смысл не трогается."""
    t = str(text or "")
    # «я понял», «Я сделал», «я не смог» — и «Понял, босс», «Сделал.» в начале предложения
    t = re.sub(r"\b([Яя])(\s+(?:уже\s+|не\s+|всё\s+|сама\s+|только что\s+)?)({})\b".format(_MASC_RE),
               lambda m: m.group(1) + m.group(2) + _fem(m.group(3)), t)
    t = re.sub(r"(^|[.!?…]\s+)({})(?=[,.!—\s])".format("|".join(w.capitalize() for w in sorted(MASC, key=len, reverse=True))),
               lambda m: m.group(1) + _fem(m.group(2)), t)
    t = re.sub(r"\b([Яя])(\s+(?:уже\s+|не\s+|всегда\s+)?)({})\b".format("|".join(ADJ)),
               lambda m: m.group(1) + m.group(2) + ADJ[m.group(3)], t)
    t = OPENERS.sub("", t.lstrip())
    t = TAILS.sub("", t)
    return t[:1].upper() + t[1:] if t else t


def describe():
    p = profile()
    return ("Мой голос: {voice}, скорость {rate:+d} %, высота {pitch:+d} Гц, громкость {volume:+d} %, паузы — {pauses}, "
            "эмоции — {emo}.".format(emo="включены" if p["emotions"] else "выключены", **p))


