"""Личность Chloe: один и тот же голос и характер, какая бы модель ни думала — Claude, Qwen, DeepSeek.

Три слоя:
1. ГОЛОС — тембр (голос Светланы + высота), скорость, громкость. Один профиль для Светланы потоком, целым файлом,
   для готовых фраз и для телефона; офлайн-голос Piper подстраивается под ту же скорость.
2. ПОДАЧА — паузы и эмоция. Паузы: длинное предложение делится на смысловые куски, «;» и «:» становятся точками,
   лишние «!!!» убираются. Эмоция — по смыслу фразы: радость (получилось) чуть быстрее и выше, сочувствие
   (не вышло, ошибка) — медленнее и ниже, серьёзность (удаление, опасность) — ровнее и ниже, вопрос — обычный.
   Сдвиги маленькие: это тот же голос в другом настроении, а не другой человек.
3. ХАРАКТЕР — карточка для мозга (в начале системной подсказки, одна для всех моделей) и «полировка» готового
   ответа: женский род о себе («понял» → «поняла»), без угодливых зачинов («Отличный вопрос!»), без «как ИИ».

Настройки — settings["persona"]: rate (−30…+30 %), pitch (−20…+20 Гц), volume, pauses (short/normal/long),
emotions (on/off). Меняются голосом: «говори медленнее», «голос пониже», «без эмоций», «верни голос как был».
"""
import re

from .settings import settings

BASE = {"voice": "ru-RU-SvetlanaNeural", "rate": 4, "pitch": -3, "volume": 0, "pauses": "normal", "emotions": True}
LIMITS = {"rate": (-30, 30), "pitch": (-20, 20), "volume": (-30, 30)}
# настроение → (скорость %, высота Гц): небольшие сдвиги от основного голоса
MOODS = {"neutral": (0, 0), "joy": (5, 3), "soft": (-6, -3), "serious": (-4, -2)}
MOOD_RU = {"neutral": "ровно", "joy": "радостно", "soft": "мягко", "serious": "серьёзно"}

JOY = re.compile(r"\b(готово|получилось|отлично|сделала|нашла|включила|запустила|ура|поздравля|молодец|успешно)\w*", re.I)
SOFT = re.compile(r"\b(к сожалению|не получилось|не вышло|не смогла|ошибк|не удалось|извин|прости|сломал|не отвечает|недоступ)\w*", re.I)
SERIOUS = re.compile(r"\b(удал|осторожн|внимани|опасн|необратим|нельзя|запрещ|угроз|пароль|ключ\w* api|списан)\w*", re.I)


def profile():
    p = dict(BASE)
    p.update({k: v for k, v in (settings.get("persona") or {}).items() if k in BASE})
    for k, (lo, hi) in LIMITS.items():
        p[k] = max(lo, min(hi, int(p[k])))
    return p


def change(**kw):
    """Поменять профиль (то, что сказал пользователь). Возвращает новый профиль."""
    cur = dict(settings.get("persona") or {})
    for k, v in kw.items():
        if k in BASE and v is not None:
            cur[k] = v
    settings.set("persona", cur)
    return profile()


def reset():
    settings.set("persona", {})
    return profile()


def signature():
    """Отпечаток профиля — для готовых фраз: поменяли голос — фразы запишутся заново."""
    p = profile()
    return "{voice}/{rate}/{pitch}/{volume}/{pauses}".format(**p)


# --- подача ---
def mood(text):
    if not profile()["emotions"]:
        return "neutral"
    t = text or ""
    if SERIOUS.search(t):
        return "serious"
    if SOFT.search(t):
        return "soft"
    if JOY.search(t):
        return "joy"
    return "neutral"


def edge_args(text):
    """rate/pitch/volume для edge-tts: профиль + настроение этой части ответа."""
    p = profile()
    dr, dp = MOODS[mood(text)]
    rate, pitch = p["rate"] + dr, p["pitch"] + dp
    return {"rate": "{:+d}%".format(rate), "pitch": "{:+d}Hz".format(pitch), "volume": "{:+d}%".format(p["volume"])}


def piper_length(text=""):
    """Скорость офлайн-голоса как у основного: length_scale (больше — медленнее)."""
    p = profile()
    dr, _ = MOODS[mood(text)]
    return round(1.0 / (1 + (p["rate"] + dr) / 100.0), 3)


LONG_SENTENCE = {"short": 260, "normal": 170, "long": 110}


def shape(text):
    """Паузы: где сказать на одном дыхании, где остановиться. Слова не меняются — только знаки."""
    p = profile()
    t = re.sub(r"\s*;\s*", ". ", text)
    t = re.sub(r"([!?])\1+", r"\1", t)                       # «!!!» → «!»
    t = re.sub(r"\.{4,}", "…", t)
    t = re.sub(r"\s+—\s+", " — ", t)
    limit = LONG_SENTENCE.get(p["pauses"], 170)
    out = []
    for s in re.split(r"(?<=[.!?…])\s+", t.strip()):
        while len(s) > limit:                               # длинное — на вдох: по запятой ближе к середине
            cut = [m.start() for m in re.finditer(r",\s", s) if limit * 0.4 < m.start() < limit]
            if not cut:
                break
            i = cut[-1]
            head, s = s[:i].rstrip() + ".", s[i + 1:].strip()
            out.append(head)
            if s:
                s = s[0].upper() + s[1:]
        if s:
            out.append(s)
    if p["pauses"] == "long":                               # неторопливо: пауза после обращения
        out = [re.sub(r"^(Босс|Слушай|Смотри),\s", r"\1… ", x) for x in out]
    return " ".join(out)


