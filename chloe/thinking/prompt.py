def city_text():
    c = settings.get("city")
    return ", ".join(x for x in (c["name"], c.get("country")) if x) if c else "пока неизвестен"


def recent_talk():
    """Краткосрочная память: последние реплики за несколько часов — переживает перезапуск и длинные задачи."""
    from ..journal import journal

    rows = journal.talk()
    if not rows:
        return ""
    lines = ["[{}] {}: {}".format(time.strftime("%H:%M", time.localtime(r["ts"])),
                                   "Пользователь" if r["kind"] == "heard" else "Ты", r["title"][:220]) for r in rows]
    return ("Недавний разговор (краткосрочная память за последние часы, в том числе до перезапуска; "
            "опирайся на него, когда пользователь говорит «это», «как я говорил», «продолжи»):\n" + "\n".join(lines) + "\n")


